#!/usr/bin/env python3
"""Write the artifact demo round into a folder: synthetic media (tones, a poster, a short silent clip), the page and a
decisions.json that points at it. Standard library only, except that the clip is made with `ffmpeg` when it is on PATH
(without it the page shows the poster and the <video> has no source).

    python examples/artifact-demo/make_demo.py OUTDIR
    mockreview create --title "Artifact demo" --decisions OUTDIR/decisions.json ...

Nothing here is real data: the names are made up and the sounds are plain sine bursts.
"""

import json
import math
import random
import shutil
import struct
import subprocess
import sys
import wave
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
RATE = 22050


def tone(path, notes, ms, decay=8.0, noise=0.0):
    """A short mono 16-bit WAV: summed sine `notes` (Hz) with an exponential decay and optional noise."""
    rng = random.Random(7)
    n = RATE * ms // 1000
    frames = bytearray()
    for i in range(n):
        t = i / RATE
        env = math.exp(-decay * t / (ms / 1000))
        v = sum(math.sin(2 * math.pi * f * t) for f in notes) / max(len(notes), 1)
        v = (v * (1 - noise) + rng.uniform(-1, 1) * noise) * env
        frames += struct.pack("<h", int(max(-1, min(1, v)) * 0.6 * 32767))
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(bytes(frames))


def png(path, w, h):
    """A flat green gradient PNG (a stand-in for a video frame)."""
    rows = bytearray()
    for y in range(h):
        rows.append(0)
        for x in range(w):
            k = (x + y) / (w + h)
            rows += bytes((int(14 + 30 * k), int(31 + 90 * k), int(22 + 50 * k)))
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b""))


def clip(path):
    """A 4 s 640x360 silent test pattern; False when ffmpeg is not installed."""
    ff = shutil.which("ffmpeg")
    if not ff:
        return False
    r = subprocess.run([ff, "-v", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=24:duration=4",
                        "-pix_fmt", "yuv420p", "-c:v", "libx264", "-preset", "veryfast", "-crf", "34", "-movflags", "+faststart",
                        str(path)], stdin=subprocess.DEVNULL, capture_output=True, timeout=120)
    return r.returncode == 0 and path.is_file()


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    out = Path(argv[1]).resolve()
    page_dir = out / "page"          # the page and its media live apart from decisions.json (a sibling assets/ would be copied too)
    assets = page_dir / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    tone(assets / "click.wav", [1800], 80, decay=14)
    tone(assets / "tick.wav", [900, 1350], 120, decay=10, noise=0.2)
    tone(assets / "whoosh.wav", [300, 450], 600, decay=4, noise=0.7)
    tone(assets / "chime.wav", [880, 1320, 1760], 700, decay=5)
    png(assets / "poster.png", 640, 360)
    page = (HERE / "page.html").read_text(encoding="utf-8")
    if not clip(assets / "film.mp4"):
        page = page.replace('<source src="assets/film.mp4" type="video/mp4">', "")
        print("ffmpeg not found: the video has a poster and no source", file=sys.stderr)
    (page_dir / "page.html").write_text(page, encoding="utf-8")
    dec = {
        "intro": "One page with sounds, a timeline, a video and a shot list, shown as a sandboxed artifact.",
        "blocks": [
            {"type": "artifact", "id": "film", "title": "Film review", "src": str(page_dir / "page.html"),
             "text": "Play the takes, scrub the clip, and mark the page in Pin mode.", "markable": True,
             "caption": "Generated by examples/artifact-demo/make_demo.py"},
        ],
    }
    (out / "decisions.json").write_text(json.dumps(dec, indent=2) + "\n", encoding="utf-8")
    print(out / "decisions.json")


if __name__ == "__main__":
    main(sys.argv)
