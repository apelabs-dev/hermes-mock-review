#!/usr/bin/env python3
"""Generate docs/settings.md and docs/cli.md from the real plugin running on a disposable Hermes home.

    python3 scripts/gen_docs_reference.py            # rewrite the two pages
    python3 scripts/gen_docs_reference.py --check    # exit 1 when a page is stale

The script copies the plugin into a throwaway HERMES_HOME, enables it, then captures the output of
`hermes mockreview settings` and `hermes mockreview <command> --help` exactly as a user sees them.
Setting names, types, ranges and defaults come from the SPEC table in mockreview/settings.py.
Hermes refuses a HERMES_HOME outside its own data directory, so the throwaway home is created next to
the real one (default: <hermes data dir>/mockreview-docs-<pid>) and deleted afterwards. Nothing under the
real home is read or written. Needs the `hermes` CLI (>= 0.22.0) on PATH.
"""

from __future__ import annotations

import argparse
import difflib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mockreview import cli, settings  # noqa: E402

PLUGIN_FILES = ("__init__.py", "plugin.yaml", "mockreview", "skills")
GROUPS = ("look", "feedback", "hosting", "server", "housekeeping", "demo")
GROUP_TITLES = {
    "look": "Look",
    "feedback": "Feedback and wake-ups",
    "hosting": "Hosting and network",
    "server": "Board server",
    "housekeeping": "Housekeeping",
    "demo": "Live demos",
}
SECRETS = (
    ("MOCKREVIEW_WEBHOOK_SECRET", "Signs the wake-up request sent to the Hermes webhook. `hermes mockreview setup` generates it."),
    ("HERENOW_API_KEY", "Your here.now key. Needed only for public here.now hosting."),
)
HEADER = "<!-- Generated by scripts/gen_docs_reference.py from the plugin running on a disposable HERMES_HOME. Do not edit by hand. -->\n"


def run(cmd: List[str], env: Dict[str, str], timeout: int = 120) -> str:
    proc = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=timeout)
    if proc.returncode != 0:
        raise SystemExit(f"command failed ({proc.returncode}): {' '.join(cmd)}\n{proc.stderr}")
    return proc.stdout.rstrip("\n")


def command_paths() -> List[List[str]]:
    """Every subcommand path of the CLI tree, parents before children."""
    parser = argparse.ArgumentParser()
    cli.add_commands(parser)
    out: List[List[str]] = []

    def walk(p: argparse.ArgumentParser, prefix: List[str]) -> None:
        for action in p._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, sub in action.choices.items():
                    out.append(prefix + [name])
                    walk(sub, prefix + [name])

    walk(parser, [])
    return out


def shown(value) -> str:
    if isinstance(value, list):
        return ", ".join(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value) if value != "" else "(empty)"


def constraint(s: settings.Setting) -> str:
    if s.choices:
        return "one of " + ", ".join(f"`{c}`" for c in s.choices)
    if s.lo is not None and s.hi is not None:
        return f"{s.lo:g} to {s.hi:g}"
    return ""


def md(text: str) -> str:
    """Keep <placeholder> words visible: Markdown would otherwise read them as HTML tags."""
    return re.sub(r"<[a-z_]+>(?:-<[a-z_]+>)*", lambda m: f"`{m.group(0)}`", text)


def render_settings(resolved_text: str) -> str:
    lines = [HEADER, "# Settings reference\n"]
    lines.append(
        "Every setting lives under `plugins.entries.mock-review.settings` in the Hermes `config.yaml`. "
        "Set one with `hermes config set plugins.entries.mock-review.settings.<name> <value>`. "
        "Each setting also has an environment variable. A value comes from the first of these that is set:\n")
    lines.append("1. an argument on a single call (a `create` flag or a tool argument)")
    lines.append("2. the environment variable")
    lines.append("3. `config.yaml`")
    lines.append("4. the default\n")
    lines.append("Look settings and the first three feedback settings are copied into each review when it is created, "
                 "so changing them later does not alter an open review. Run `hermes mockreview settings` to see every "
                 "value and where it came from.\n")
    for group in GROUPS:
        specs = [s for s in settings.SPEC if s.group == group]
        if not specs:
            continue
        lines.append(f"## {GROUP_TITLES[group]}\n")
        for s in specs:
            extra = constraint(s)
            meta = f"{s.type}, default `{shown(s.default)}`" + (f", {extra}" if extra else "")
            lines.append(f"- `{s.name}` ({meta}). Env: `{s.env_name}`. {md(s.description)}")
        lines.append("")
    lines.append("## Secrets\n")
    lines.append("Secrets are not settings. The plugin reads them through Hermes's secret scope, so they live in the Hermes "
                 "`.env`, never in `config.yaml`.\n")
    for name, text in SECRETS:
        lines.append(f"- `{name}`: {text}")
    lines.append("\n## Output of `hermes mockreview settings`\n")
    lines.append("Captured from a fresh Hermes home with the plugin enabled and nothing configured, so every value shows its default.\n")
    lines.append("```text")
    lines.append(resolved_text)
    lines.append("```")
    return "\n".join(lines) + "\n"


def render_cli(helps: List[Tuple[str, str]]) -> str:
    lines = [HEADER, "# Command reference\n"]
    lines.append("Every command is available as `hermes mockreview <command>`. Without the Hermes plugin loader, "
                 "`bin/mockreview <command>` in a checkout runs the same code. Commands print JSON unless noted. "
                 "The text below is the real `--help` output.\n")
    for title, text in helps:
        lines.append(f"## `{title}`\n")
        lines.append("```text")
        lines.append(text)
        lines.append("```\n")
    return "\n".join(lines).rstrip("\n") + "\n"


def build(home: Path) -> Tuple[str, str]:
    plugin = home / "plugins" / "mock-review"
    plugin.mkdir(parents=True)
    for name in PLUGIN_FILES:
        src = ROOT / name
        if src.is_dir():
            shutil.copytree(src, plugin / name, ignore=shutil.ignore_patterns("__pycache__"))
        else:
            shutil.copyfile(src, plugin / name)
    env = {k: v for k, v in os.environ.items() if not k.startswith("MOCKREVIEW_")}
    env.update(HERMES_HOME=str(home), COLUMNS="80", NO_COLOR="1")
    run(["hermes", "plugins", "enable", "mock-review"], env)
    resolved = run(["hermes", "mockreview", "settings"], env)
    helps = [("hermes mockreview --help", run(["hermes", "mockreview", "--help"], env))]
    for path in command_paths():
        cmd = ["hermes", "mockreview", *path, "--help"]
        helps.append((" ".join(cmd[:-1]) + " --help", run(cmd, env)))
    return render_settings(resolved), render_cli(helps)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when docs/settings.md or docs/cli.md is stale")
    ap.add_argument("--home", help="throwaway HERMES_HOME to use (must not exist; deleted afterwards)")
    a = ap.parse_args(argv)
    if shutil.which("hermes") is None:
        print("error: the hermes CLI is not on PATH", file=sys.stderr)
        return 2
    base = settings.default_hermes_home()
    home = Path(a.home) if a.home else Path(tempfile.mkdtemp(prefix="mockreview-docs-", dir=base))
    if a.home:
        if home.exists():
            print(f"error: {home} already exists", file=sys.stderr)
            return 2
    try:
        pages = dict(zip(("settings.md", "cli.md"), build(home)))
    finally:
        shutil.rmtree(home, ignore_errors=True)
    stale = False
    for name, text in pages.items():
        target = ROOT / "docs" / name
        if a.check:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != text:
                stale = True
                sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                           f"docs/{name} (committed)", f"docs/{name} (generated)"))
        else:
            target.write_text(text, encoding="utf-8")
            print(f"wrote docs/{name} ({len(text.splitlines())} lines)")
    if a.check:
        print("generated reference pages are stale" if stale else "generated reference pages are up to date")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
